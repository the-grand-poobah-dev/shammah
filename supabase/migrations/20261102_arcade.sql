-- Arcade backend: persistent games, scores, daily seeds and achievements.
-- Safe to re-run; all writes are constrained to server-owned RPCs.
create table if not exists public.arcade_games (
  slug text primary key,
  title text not null,
  description text not null default '',
  icon text not null default 'gamepad-2',
  accent text not null default '#8b5cf6',
  kind text not null default 'quiz' check (kind in ('quiz','memory','action','trivia')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.arcade_scores (
  id uuid primary key default gen_random_uuid(),
  game_slug text not null references public.arcade_games(slug) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  score integer not null check (score >= 0 and score <= 100000),
  meta jsonb not null default '{}'::jsonb,
  duration_ms integer not null default 0 check (duration_ms >= 0 and duration_ms <= 7200000),
  created_at timestamptz not null default now()
);
create index if not exists arcade_scores_game_score_idx on public.arcade_scores(game_slug, score desc, created_at desc);
create index if not exists arcade_scores_user_game_idx on public.arcade_scores(user_id, game_slug, created_at desc);

create table if not exists public.arcade_daily (
  game_slug text not null references public.arcade_games(slug) on delete cascade,
  day date not null,
  seed text not null,
  created_at timestamptz not null default now(),
  primary key (game_slug, day)
);

create table if not exists public.arcade_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  game_slug text not null references public.arcade_games(slug) on delete cascade,
  level integer not null default 1 check (level >= 1),
  best_score integer not null default 0 check (best_score >= 0),
  plays integer not null default 0 check (plays >= 0),
  last_played_on date,
  streak integer not null default 0 check (streak >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, game_slug)
);

create table if not exists public.arcade_achievements (
  user_id uuid not null references auth.users(id) on delete cascade,
  code text not null,
  earned_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  primary key (user_id, code)
);

create table if not exists public.arcade_verses (
  id bigint generated by default as identity primary key,
  ref text not null unique,
  text text not null,
  translation text not null default 'KJV',
  created_at timestamptz not null default now()
);

create table if not exists public.arcade_questions (
  id bigint generated by default as identity primary key,
  category text not null default 'General',
  testament text not null default 'NT' check (testament in ('OT','NT')),
  book text not null,
  question text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) >= 2),
  correct_index integer not null check (correct_index >= 0),
  explanation text not null default '',
  created_at timestamptz not null default now(),
  check (correct_index < jsonb_array_length(options))
);

