create or replace function public.submit_arcade_score(
  p_user_id uuid, p_game_slug text, p_score integer, p_duration_ms integer, p_meta jsonb default '{}'::jsonb
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_best integer;
  v_previous_day date;
  v_streak integer;
  v_today date := (now() at time zone 'utc')::date;
  v_rank bigint;
begin
  if p_user_id is null or p_game_slug is null or p_score is null or p_score < 0 or p_score > 100000 then
    raise exception 'Invalid score submission';
  end if;
  if p_duration_ms is null or p_duration_ms < 1000 or p_duration_ms > 7200000 then
    raise exception 'Game duration is outside the allowed range';
  end if;
  if not exists (select 1 from public.arcade_games where slug = p_game_slug and is_active) then
    raise exception 'Game is unavailable';
  end if;
  -- Simple per-game plausibility ceilings. A server-side score is still required.
  if p_game_slug = 'scripture-scramble' and p_score > 5000 then raise exception 'Score exceeds game limit'; end if;
  if p_game_slug = 'memory-verse-match' and p_score > 10000 then raise exception 'Score exceeds game limit'; end if;
  if p_game_slug = 'bible-trivia' and p_score > 10000 then raise exception 'Score exceeds game limit'; end if;
  if p_game_slug not in ('scripture-scramble','memory-verse-match','bible-trivia') and p_score > 20000 then
    raise exception 'Score exceeds game limit';
  end if;

  insert into public.arcade_scores(game_slug,user_id,score,duration_ms,meta)
  values (p_game_slug,p_user_id,p_score,p_duration_ms,coalesce(p_meta,'{}'::jsonb));

  select best_score, last_played_on, streak into v_best, v_previous_day, v_streak
    from public.arcade_progress where user_id=p_user_id and game_slug=p_game_slug for update;
  if not found then
    v_best := 0; v_previous_day := null; v_streak := 0;
  end if;
  if v_previous_day = v_today then
    v_streak := greatest(v_streak,1);
  elsif v_previous_day = v_today - 1 then
    v_streak := v_streak + 1;
  else
    v_streak := 1;
  end if;

  insert into public.arcade_progress(user_id,game_slug,best_score,plays,last_played_on,streak,updated_at)
  values (p_user_id,p_game_slug,greatest(v_best,p_score),1,v_today,v_streak,now())
  on conflict (user_id,game_slug) do update set
    best_score=greatest(public.arcade_progress.best_score,excluded.best_score),
    plays=public.arcade_progress.plays+1,
    last_played_on=excluded.last_played_on,
    streak=excluded.streak,
    level=greatest(public.arcade_progress.level, 1 + (greatest(public.arcade_progress.best_score,excluded.best_score) / 1000)),
    updated_at=now();

  insert into public.arcade_achievements(user_id,code,metadata)
  values (p_user_id,'arcade-first-win',jsonb_build_object('game',p_game_slug))
  on conflict (user_id,code) do nothing;
  if p_score > 0 then
    insert into public.arcade_achievements(user_id,code,metadata)
    values (p_user_id,'arcade-first-score',jsonb_build_object('game',p_game_slug))
    on conflict (user_id,code) do nothing;
  end if;
  if v_streak >= 7 then
    insert into public.arcade_achievements(user_id,code,metadata)
    values (p_user_id,'arcade-7-day-streak',jsonb_build_object('game',p_game_slug,'streak',v_streak))
    on conflict (user_id,code) do nothing;
  end if;
  if p_meta ? 'perfect' and (p_meta->>'perfect') = 'true' then
    insert into public.arcade_achievements(user_id,code,metadata)
    values (p_user_id,'arcade-perfect-round',jsonb_build_object('game',p_game_slug))
    on conflict (user_id,code) do nothing;
  end if;

  select count(*) + 1 into v_rank from public.arcade_scores
    where game_slug=p_game_slug and score > p_score;
  return jsonb_build_object('ok',true,'best_score',greatest(v_best,p_score),'streak',v_streak,'rank',v_rank);
end;
$$;

create or replace function public.arcade_leaderboard(p_game_slug text, p_scope text default 'weekly')
returns table(user_id uuid, score integer, created_at timestamptz, display_name text)
language sql stable security definer set search_path = public, pg_temp as $$
  select s.user_id, max(s.score)::integer as score, max(s.created_at) as created_at,
    coalesce(nullif(u.raw_user_meta_data->>'full_name',''), nullif(u.raw_user_meta_data->>'name',''), 'Faithful player') as display_name
  from public.arcade_scores s join auth.users u on u.id=s.user_id
  where s.game_slug=p_game_slug
    and (p_scope='all' or (p_scope='daily' and s.created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc')
      or (p_scope='weekly' and s.created_at >= now() - interval '7 days'))
  group by s.user_id, u.raw_user_meta_data
  order by max(s.score) desc, max(s.created_at) asc
  limit 50;
$$;

create or replace function public.arcade_daily_seed(p_game_slug text)
returns text language plpgsql security definer set search_path = public, pg_temp as $$
declare v_day date := (now() at time zone 'utc')::date; v_seed text;
begin
  if not exists (select 1 from public.arcade_games where slug=p_game_slug and is_active) then raise exception 'Game unavailable'; end if;
  insert into public.arcade_daily(game_slug,day,seed)
  values (p_game_slug,v_day,encode(digest(p_game_slug || ':' || v_day::text,'sha256'),'hex'))
  on conflict (game_slug,day) do nothing;
  select seed into v_seed from public.arcade_daily where game_slug=p_game_slug and day=v_day;
  return v_seed;
end;
$$;

