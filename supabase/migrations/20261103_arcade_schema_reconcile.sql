begin
  if p_user_id is null or p_game_slug is null or p_score is null or p_score < 0 or p_score > 100000 then
    raise exception 'Invalid score submission';
  end if;
  if p_duration_ms is null or p_duration_ms < 1000 or p_duration_ms > 7200000 then
    raise exception 'Game duration is outside the allowed range';
  end if;
